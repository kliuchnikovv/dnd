package threshold

import "github.com/kliuchnikovv/dnd/core"

// Сложность — закрытое множество из трёх ступеней. Больше ступеней не нужно:
// порог задаёт КЛАСС задачи, а тонкую настройку позиции делает ситуативное
// слагаемое.
const (
	DifficultyEasy   = "easy"
	DifficultyNormal = "normal"
	DifficultyHard   = "hard"
)

// DifficultyFor назначает сложность действию. Функция чистая: одна и та же
// позиция даёт один и тот же порог, всегда.
//
// Существует ради несудимого действия. Раньше порог у него был только один —
// «Норма», — и позиция входила в бросок лишь слагаемым: удар по открытой в
// упор цели и та же попытка против сопротивляющегося противника получали одну
// базовую сложность. Живой Мастер закрывал эту дыру на глаз, то есть двигал
// матожидание броска прозой, — ровно то, что запрещает ADR-0001.
//
// Интент в подписи есть, но НИ ОДНО его поле сюда не входит, и это не
// недоделка, а само правило: как бы действие ни сформулировали и какой бы
// класс ни предложил парсер по свободному тексту, порог решает позиция.
// Подсказка формы над костью бесправна — иначе свободный ввод стал бы способом
// торговаться за сложность.
func DifficultyFor(_ core.Intent, view core.SceneView) string {
	// Авторский гейт сильнее формулы. Автор дела знает про своё дело больше,
	// чем закрытый список сигналов, и это сохранённое расхождение из M1a, а не
	// временный костыль.
	if view.GateThreshold != "" {
		return view.GateThreshold
	}

	// Среда, которую нечем компенсировать, — то же противодействие, только со
	// стороны места, а не воли. Инструмент её снимает по тому же правилу, что и
	// в слагаемом: фонарь возвращает к норме, а не делает лучше нормы.
	harder := view.Opposed || adverseUncompensated(view)
	easier := view.Exposed

	// Ступень ровно одна и никогда больше: две вниз сделали бы попадание
	// автоматическим, две вверх — невозможным. Встречные сигналы (связанный, но
	// злой противник) друг друга гасят: ни один не отбрасывается молча, просто
	// ступени нет.
	switch {
	case harder == easier:
		return DifficultyNormal
	case harder:
		return DifficultyHard
	default:
		return DifficultyEasy
	}
}

// adverseUncompensated — обстановка мешает и снять помеху нечем. Список тегов
// тот же, что у слагаемого: два места правды о том, какая среда враждебна,
// разошлись бы молча.
func adverseUncompensated(view core.SceneView) bool {
	if len(view.Tools) > 0 {
		return false
	}
	for _, tag := range adverseTags {
		if view.HasTag(tag) {
			return true
		}
	}
	return false
}
