package threshold

import "github.com/kliuchnikovv/dnd/core"

// Сложность — закрытое множество из трёх ступеней. Больше ступеней не нужно:
// порог задаёт КЛАСС задачи, а тонкую настройку позиции делает ситуативное
// слагаемое.
const (
	DifficultyEasy   = "easy"
	DifficultyNormal = "normal"
	DifficultyHard   = "hard"
)

// DifficultyFor назначает сложность действию. Функция чистая: одна и та же
// позиция даёт один и тот же порог, всегда.
//
// По D&D (и прото §6) DC — это трудность ЗАДАЧИ САМОЙ ПО СЕБЕ; обстановка
// (сопротивление цели, открытость, среда) на порог НЕ влияет — она идёт через
// advantage/disadvantage (см. Vantage). Поэтому порог задаёт только автор дела;
// без авторского гейта — medium. Раньше Opposed/Exposed двигали порог на ступень;
// теперь тот же факт выражен помехой/преимуществом 2d20, чтобы за одно
// обстоятельство не платить дважды.
//
// Интент в подписи есть, но НИ ОДНО его поле сюда не входит, и это не
// недоделка, а само правило: как бы действие ни сформулировали и какой бы
// класс ни предложил парсер по свободному тексту, порог решает автор/задача.
// Подсказка формы над костью бесправна — иначе свободный ввод стал бы способом
// торговаться за сложность.
func DifficultyFor(_ core.Intent, view core.SceneView) string {
	// Авторский гейт сильнее формулы. Автор дела знает про своё дело больше,
	// чем закрытый список сигналов, и это сохранённое расхождение из M1a, а не
	// временный костыль.
	if view.GateThreshold != "" {
		return view.GateThreshold
	}
	return DifficultyNormal
}
