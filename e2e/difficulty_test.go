package e2e

import (
	"math/rand"
	"testing"

	"github.com/kliuchnikovv/dnd/rules/threshold"
)

// Сложность, которую ядро назначает почти всегда одну и ту же, — это не
// суждение о позиции, а константа, поставленная не туда. Найти такую надо
// здесь, а не на катке: на катке она видна как «почему-то всё тяжело», и к
// тому времени под неё уже подстроились авторские дела.
//
// Инструмент тот же, что у теста факторов: случайные пробы по реальному делу,
// а не выдуманный набор срезов. Набор срезов измерял бы, как я его собрал.
const difficultyTooOften = 0.60

func TestNoDifficultyIsAssignedAlmostAlways(t *testing.T) {
	assigned := map[string]int{}
	gated, ungated := 0, 0

	for seed := int64(0); seed < 200; seed++ {
		g := newGame(t, seed)
		r := rand.New(rand.NewSource(seed))
		for i := 0; i < 40; i++ {
			in, ok := randomProbe(g, r)
			if !ok {
				moveRandomly(g, r)
				continue
			}
			view := g.SceneView(in)
			// Судимое авторским гейтом действие меряет разметку дела, а не
			// функцию: там сложность назначил человек, и её частота — вопрос
			// к автору.
			if view.GateThreshold != "" {
				gated++
			} else {
				assigned[threshold.DifficultyFor(in, view)]++
				ungated++
			}
			g.Apply(in)
			if r.Intn(3) == 0 {
				moveRandomly(g, r)
			}
		}
	}

	t.Logf("несудимых гейтом бросков %d из %d", ungated, ungated+gated)
	if ungated == 0 {
		t.Fatal("несудимых бросков не нашлось — измерять нечего, выборка не о том")
	}

	// «Норма» печатается, но не судится: это БАЗА, а не ступень. База,
	// покрывающая большинство бросков, — правильно: большинство позиций
	// нейтральны, и требовать от неё редкости значило бы требовать, чтобы
	// сложность колебалась без повода.
	base := float64(assigned[threshold.DifficultyNormal]) / float64(ungated)
	t.Logf("%-6s (база) назначается в %.1f%% несудимых бросков",
		threshold.DifficultyNormal, base*100)

	// Судятся ступени. Ступень, которая срабатывает чаще, чем не срабатывает,
	// уже не сдвиг относительно базы — это новая база, объявленная сдвигом.
	//
	// Порознь нижней границы у ступеней нет: «Легко» сейчас честно не
	// срабатывает ни разу, потому что состояния беспомощной цели в M1a ещё нет
	// (см. Exposed в core.SceneView). Судить его редкость значило бы требовать
	// от дела боя, которого в нём нет. Когда такое состояние появится, нижняя
	// граница для «Легко» — это место.
	moved := 0
	for _, d := range []string{threshold.DifficultyEasy, threshold.DifficultyHard} {
		moved += assigned[d]
		rate := float64(assigned[d]) / float64(ungated)
		t.Logf("%-6s назначается в %.1f%% несудимых бросков", d, rate*100)
		if rate > difficultyTooOften {
			t.Errorf("ступень %s срабатывает в %.1f%% несудимых бросков — это не сдвиг от базы, а новая база",
				d, rate*100)
		}
	}

	// Обратная поломка: функция, которая не двигает порог НИКОГДА, — это
	// прежняя флат-Норма под новым именем. Молча она выглядит как зелёный тест.
	if moved == 0 {
		t.Error("порог не сдвинулся ни разу — позиция на сложность не влияет вообще")
	}
}
