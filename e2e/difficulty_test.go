package e2e

import (
	"math/rand"
	"testing"

	"github.com/kliuchnikovv/dnd/rules/threshold"
)

// Обстановка теперь идёт преимуществом/помехой (2d20), а не сдвигом порога:
// сложность задаёт автор дела, а среда/позиция — vantage (см. ADR-0008-мерж,
// решение «среда→adv/dis»; rules/threshold/vantage.go). Этот тест — мера того же
// рода, что и раньше стоял на сложности: случайные пробы по реальному делу, а не
// выдуманный набор срезов (набор мерил бы, как я его собрал).
//
// Что меряем и почему именно так:
//   - vantage ДОЛЖЕН иногда срабатывать: механизм, который не двигает ничего
//     никогда, — это прежняя флат-Норма под новым именем, зелёная молча.
//   - «ровно» (none) — это БАЗА, а не поломка: нейтральные позиции нормальны.
//   - Потолка «слишком часто» на помеху здесь НЕТ намеренно. Мера показала:
//     на реальных M1a-делах disadvantage срабатывает ~69%, advantage ~0%
//     (в M1a нет состояния беспомощной цели — Exposed не ставится; adverse-среда,
//     тьма/дождь, стоит примерно в половине узлов). Это ОСОЗНАННО принятая цена
//     решения «среда→adv/dis»: для хоррор-виньетки «темно и опасно = помеха» —
//     тема, а не баг. Когда в данные придёт Exposed-состояние — здесь появится и
//     ненулевой advantage. Цифры логируются, чтобы дрейф был виден на мере.
func TestVantageEngagesButIsNotFlat(t *testing.T) {
	dist := map[int]int{}
	total := 0

	for seed := int64(0); seed < 200; seed++ {
		g := newGame(t, seed)
		r := rand.New(rand.NewSource(seed))
		for i := 0; i < 40; i++ {
			in, ok := randomProbe(g, r)
			if !ok {
				moveRandomly(g, r)
				continue
			}
			dist[threshold.Vantage(in, g.SceneView(in))]++
			total++
			g.Apply(in)
			if r.Intn(3) == 0 {
				moveRandomly(g, r)
			}
		}
	}

	if total == 0 {
		t.Fatal("проб не нашлось — измерять нечего, выборка не о том")
	}
	pct := func(n int) float64 { return 100 * float64(n) / float64(total) }
	t.Logf("vantage по %d пробам: преимущество %.1f%% · помеха %.1f%% · ровно %.1f%%",
		total, pct(dist[+1]), pct(dist[-1]), pct(dist[0]))

	// Механизм реально работает: хоть иногда обстановка даёт помеху/преимущество.
	if dist[+1]+dist[-1] == 0 {
		t.Error("vantage не сработал ни разу — обстановка на бросок не влияет вовсе (флат-Норма под новым именем)")
	}
	// «Ровно» существует как база: не всякая позиция обострена. Если vantage
	// срабатывает ВСЕГДА, это уже не учёт обстановки, а вторая сложность.
	if dist[0] == 0 {
		t.Error("нейтральных позиций не нашлось — vantage стал постоянным, а не учётом обстановки")
	}
}
