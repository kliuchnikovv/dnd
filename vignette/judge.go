package vignette

// Судья — ХОЛОДНЫЙ адъюдикатор: превращает свободный ввод игрока в типизированный
// Ruling, слепой к желанию игрока и к тайне сцены (правды не видит). Ядро потом
// исполняет вердикт честной костью. idle/делимитер/мета-страховка живут ЗДЕСЬ —
// как робастность и гигиена (чтобы игрок не проиграл на мусоре/опечатке и чтобы
// инъекция не доехала до нарратива), а НЕ как защита от враждебного игрока:
// анти-лик держится конструкцией (Мастер не получает правду), а не этими
// фильтрами (ADR-0007/0009).

// JudgeObject — присутствующий объект сцены (что видно), для сопоставления цели.
type JudgeObject struct {
	ID   string
	Name string
}

// JudgeView — что судья видит: присутствующие объекты, положение, атмосфера,
// физический контекст. Ни правды, ни закрытых тиров здесь нет.
type JudgeView struct {
	Objects  []JudgeObject
	Position string
	Ambient  string
	OffPath  bool
	Mire     int
}

// Judge — превращает фразу игрока в Ruling.
type Judge interface {
	Rule(text string, v JudgeView) Ruling
}
