package core

import (
	"sort"

	"github.com/kliuchnikovv/dnd/store"
)

// HintAfter — сколько ходов подряд впустую копится, прежде чем сработает
// чутьё. Подсказка на каждом ходу — не помощь, а чтение решения вслух;
// подсказка никогда — это игрок, застрявший в первой сессии и закрывший
// консоль.
const HintAfter = 3

// Hint возвращает подсказку чутья, если расследование встало. Указывает она на
// ЦЕЛЬ, а не на ответ: строку пишет автор дела, движок только выбирает момент.
//
// Говорящего у подсказки нет намеренно. Раньше её произносил напарник-NPC — и
// оказывался в ответе за слова, которые выбрал движок: подсказка называет
// человека или запись (в «Гавани» четыре из шести), то есть ровно те две
// категории, которые гвард обязан рубить как выдумку персонажа. Единственное
// место, где выбранное движком знание законно, — голова самого игрока.
//
// Выбирается первый неизвестный факт, к держателю которого можно подойти
// прямо сейчас. Порядок обхода стабилен: одна и та же ситуация даёт одну и ту
// же подсказку, иначе прогон перестаёт быть воспроизводимым.
func (g *Game) Hint() (string, bool) {
	if g.dry < HintAfter {
		return "", false
	}
	ids := make([]store.FactID, 0, len(g.Hints))
	for id := range g.Hints {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })

	for _, id := range ids {
		if g.K.Knows(id) || g.hinted[id] {
			continue
		}
		if !g.holderSeen(id) {
			continue
		}
		g.hinted[id] = true
		g.dry = 0
		return g.Hints[id], true
	}
	return "", false
}

// holderSeen — держатель факта стоит там, где игрок УЖЕ БЫЛ. Не в смежном
// узле: «туда можно дойти» и «ты там был» — разные вещи, и чутьё вправе
// опираться только на второе. Раньше проверялась смежность, и живой прогон
// получил на Пристани подсказку про кузнеца, которого не встречал: имя и мотив
// взялись из ниоткуда, то есть чутьё работало оракулом.
//
// Помощь при этом не исчезает: в стартовом узле игрок стоит, значит его
// держатели доступны с первого хода.
func (g *Game) holderSeen(f store.FactID) bool {
	for _, h := range g.DB.HoldersOf(f) {
		e, ok := g.DB.Entities[h.HolderID]
		if !ok {
			continue
		}
		if g.visited[e.Node] {
			return true
		}
	}
	return false
}

// noteTurn ведёт счётчик ходов вхолостую. Считаются только жёсткие пробы:
// осмотреться и подумать — не «застрял».
func (g *Game) noteTurn(def VerbDef, learned int) {
	if !def.Hard {
		return
	}
	if learned > 0 {
		g.dry = 0
		return
	}
	g.dry++
}
