package rubric

// applicability.go — различение «пункт не применим к этому ходу» и «пункт не
// оценён».
//
// Зачем. В отчёте вердикт NA по двум РАЗНЫМ причинам:
//
//   - ход не даёт материала для пункта (не было броска → A2/A3/A4 не о чем
//     судить). Это НОРМА, не беда.
//   - пункт не оценён, потому что не подключён LLM-судья (или модель
//     ответила ерундой). Это ПРОБЕЛ, и его надо видеть.
//
// Если смешать их в одно «–», отчёт превращается в воду: нельзя отличить
// «Мастер не нарушил A2, потому что A2 не применим» от «A2 никто не
// проверял». Поэтому Applicability говорит, чего ждать по каждому пункту.

// Applicability — что можно сказать о применимости пункта к ходу.
type Applicability int

const (
	// Applies — пункт применим: у хода есть материал, и пункт должен быть
	// оценён (auto-судьёй или LLM-судьёй).
	Applies Applicability = iota
	// NotApplicable — пункт не применим к ходу по существу (нет броска, нет
	// бита, нет NPC-броска). Вердикт NA здесь — правильный ответ.
	NotApplicable
	// NeedsJudge — применимость решает судья (семантика прозы). Пока
	// LLM-судья не подключён, пункт останется NA — и это пробел, а не норма.
	NeedsJudge
)

func (a Applicability) String() string {
	switch a {
	case Applies:
		return "применим"
	case NotApplicable:
		return "не применим"
	default:
		return "нужен судья"
	}
}

// ApplicabilityOf — что ожидать по пункту на этом ходу.
//
// Структурно определяемые (по содержимому хода):
//
//	A2, A3 — нужен бросок: без него нечего показывать и подписывать.
//	A4     — нужен бросок: без него нет ни успеха, ни провала.
//	C10    — нужен бросок мира/противника.
//	D13    — нужен ключ-ответа сцены: нечего проверять на утечку.
//
// C11 («часы на виду») структурно НЕ определяется: нужен бит ИЛИ видимое
// давление, но «видно ли это игроку» — вопрос смысла прозы. Поэтому C11
// уходит LLM-судье.
//
// Всё остальное (A1, B5–B9, C12) тоже решается по смыслу прозы — NeedsJudge.
func ApplicabilityOf(item Item, rec TurnRecord) Applicability {
	switch item {
	case A2, A3, A4:
		if !rec.HasRoll() {
			// A2 ещё применим без броска, если Мастер говорит о кости
			// (ход 1 в Эталоне: «бросаю в терминале»).
			if item == A2 && rec.ExpectsDie {
				return Applies
			}
			return NotApplicable
		}
		return Applies
	case C10:
		if !rec.NpcRolled {
			return NotApplicable
		}
		return Applies
	case D13:
		if rec.SceneTruth == "" && len(rec.ClosedTiers) == 0 {
			return NotApplicable
		}
		return Applies
	case A1, B5, B6, B7, C8, C9, C11, C12:
		return NeedsJudge
	default:
		return NeedsJudge
	}
}

// GapVerdicts — вердикты, которые выглядят как «прошло/не прошло», но на
// деле оставлены пустыми из-за неподключённого судьи. Это то, что нужно
// закрыть перед тем, как считать этал пройденным.
//
// Возвращает список пунктов с NA, которые ПРИМЕНИМЫ по существу, но не были
// оценены. Пустой список = все применимые пункты оценены.
func GapVerdicts(vs []Verdict) []Item {
	var gaps []Item
	for _, v := range vs {
		if v.Outcome != OutcomeNA {
			continue
		}
		// Пропуск по существу (нет броска) — не пробел. Пробел — это когда
		// применимость не отрицается структурно.
		if v.Source == KindAuto {
			continue
		}
		gaps = append(gaps, v.Item)
	}
	return gaps
}
