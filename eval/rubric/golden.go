// GoldenNpcRoll — бросок мира/противника на ходе. Для C10 («мир тоже играет»):
// тварь бросает по той же честной кости, и её бросок виден игроку.
type GoldenNpcRoll struct {
	D20    int
	Mod    int
	DC     int
	Total  int
	Margin int
	Line   string
}

// GoldenTurn — один ход золотой катки.
//
// Поля делятся на две группы:
//
//	ЧТО ЗНАЕТ МАСТЕР (рамка для прозы):
//	   Frame   — механически произошедшее; из этого Мастер пишет.
//	   Outcome — факты, которые игрок ЗАСЛУЖИЛ и которые уходят в канон.
//
//	ЧТО ЗНАЕТ РУБРИКА (эталон для оценки):
//	   Roll/NpcRoll — кости, чтобы оценивать A2/C10.
//	   Revealed     — всё, что открыто на данный момент (для D13: «заслужено»).
//	   StateNote/Beat — состояние и эскалация (для A4/C11).
//
// ВАЖНО: мастер получает ТОЛЬКО Frame + Outcome + Setting. Roll/Revealed/
// SceneTruth — только рубрике. Это повторяет прод-разделение (ADR-0008):
// Мастер не видит ключ-ответа.
type GoldenTurn struct {
	// Input — заявка игрока (дословно из Эталона).
	Input string

	// Frame — что произошло, рамка для прозы. Описывает исход хода так,
	// чтобы Мастер мог его развернуть, не выдумывая механику заново.
	Frame string

	// Outcome — факты, которые игрок заслужил на этом ходу. Уходят в канон
	// и в прозу. Порядок = порядок появления.
	Outcome []string

	// Roll — бросок игрока в каноничном виде ядра:
	// «бросок: d20=16+0 = 16 против 14 · +2». Пусто — броска не было.
	Roll string
	// Числа броска для машинных проверок A2/A4.
	RollD20, RollMod, RollDC, RollTotal, RollMargin int
	// RollNatural — 1 или 20 для натуральных бросков; 0 иначе.
	RollNatural int

	// NpcRoll — бросок мира/противника (C10). nil — в этом ходу мир не бросал.
	NpcRoll *GoldenNpcRoll

	// Revealed — всё открытое знание на КОНЕЦ хода (накопительно). Это
	// «заслужено» для D13.
	Revealed []string

	// StateNote — нейтральное положение (для контекста и A4).
	StateNote string

	// Beat — эскалация (C11): «часы на виду».
	Beat string

	// Note — человеческая пометка из Эталона: что сделал Мастер-человек и
	// какие пункты сработали. Нужна для отчёта и для глаза проверяющего.
	Note string

	// EtalonTags — пункты Эталона, которые сработали у МАСТЕРА-ЧЕЛОВЕКА на
	// этом ходу (скобки в документе). Это верхняя планка: ИИ-Мастер должен
	// вытянуть не меньше. Отчёт сравнивает теги с фактическими вердиктами и
	// показывает, что не вытянуто.
	//
	// ВНИМАНИЕ: теги в документе — это «что сработало», а не «что применимо».
	// Применимость рубрика считает сама (ApplicabilityOf).
	EtalonTags []Item

	// DieTalk — на этом ходу Мастер говорит о кости (например, на старте
	// «бросаю в терминале»). Тогда A2 применим, хотя броска ещё не было:
	// проверяется, что кость показана игроку как честная.
	DieTalk bool
}

