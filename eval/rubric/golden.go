// golden.go — золотой прогон «Тихий Дол» как данные.
//
// Что это. Живая катка человека-Мастера из
// docs/design/2026-09-02-master-reference-standard.md (§«Золотой прогон»)
// разложена на ходы: заявка игрока, механический исход, что открылось, что
// бросил мир. Эталон прямо требует (§«Эвал ИИ-мастера», п.1):
//
//	«Прогнать ИИ-мастера по ходам катки "Тихий Дол" (те же заявки игрока) и
//	 оценить каждый ход по применимым пунктам A–D. Человек-Мастер здесь —
//	 верхняя планка.»
//
// То есть оценивается МАСТЕР (его проза), а не движок. Механика из человеческой
// катки берётся как РЕФЕРЕНС: те же кости, тот же исход, то же раскрытое
// знание. ИИ-Мастер получает заявку игрока и рамку исхода, и пишет прозу
// сам — а рубрика оценивает именно эту прозу.
//
// Почему не прогон через движок (vignette/дnd5e):
//   - катка в Эталоне — это чужой формат (порог d20+атрибут+тег, лестница
//     ранений, grit), а не текущий виньетковый движок;
//   - главное в эвале — речь Мастера, а не воспроизведение бросков;
//   - зафиксированная механика делает эвал СРАВНИМЫМ: две модели, один и тот
//     же вход, разница только в прозе.
//
// Что здесь НЕ делается: механика не пересчитывается и не проверяется — это
// зона собственных тестов движка. Здесь она эталонная.

