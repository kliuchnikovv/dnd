// ToRecord — превращает ход золотой катки в TurnRecord рубрики. masterOutput —
// проза, написанная ИИ-Мастером (или человеком-Мастером для референсного
// прогона).
//
// SceneTruth на всех ходах = GoldenSecret: D13 сравнивает прозу с ключом-
// ответом и с тем, что игрок УЖЕ ЗАСЛУЖИЛ (Revealed). Пока тайна не
// заслужена, её появление в прозе — утечка; заслужена — легальное раскрытие.
func (t GoldenTurn) ToRecord(masterOutput string) TurnRecord {
	rec := TurnRecord{
		Input:        t.Input,
		MasterOutput: masterOutput,
		Revealed:     append([]string{}, t.Revealed...),
		StateNote:    t.StateNote,
		Beat:         t.Beat,
		SceneTruth:   GoldenSecret,
		ExpectsDie:   t.DieTalk,
		EtalonTags:   append([]Item{}, t.EtalonTags...),
	}
	if t.Roll != "" {
		rec.Roll.Line = t.Roll
		rec.Roll.D20 = t.RollD20
		rec.Roll.Mod = t.RollMod
		rec.Roll.DC = t.RollDC
		rec.Roll.Total = t.RollTotal
		rec.Roll.Margin = t.RollMargin
		rec.Roll.Natural = t.RollNatural
	}
	if t.NpcRoll != nil {
		rec.NpcRolled = true
		rec.NpcRoll.D20 = t.NpcRoll.D20
		rec.NpcRoll.Margin = t.NpcRoll.Margin
	}
	return rec
}

// CanonSoFar — накопленный канон к началу хода: то, что Мастер уже знает как
// заслуженное знание и что уходит в его прозу. Отдельные факты хода не
// дублируются: рамка уже несёт Outcome.
func CanonSoFar(turns []GoldenTurn, idx int) []string {
	var out []string
	for i := 0; i < idx && i < len(turns); i++ {
		out = append(out, turns[i].Outcome...)
	}
	return out
}

// GoldenPrompt — что показывать Мастеру на конкретном ходе: рамка (что
// произошло) + канон (что игрок уже знает). Ничего больше — ни ключа-ответа,
// ни чисел рубрики.
//
// Если рамка пуста, Мастеру нечего описывать, и ход пропускается (такое
// возможно только при кривом сценарии — обычные ходы всегда с рамкой).
func GoldenPrompt(turns []GoldenTurn, idx int) (frame string, canon []string) {
	if idx < 0 || idx >= len(turns) {
		return "", nil
	}
	t := turns[idx]
	if strings.TrimSpace(t.Frame) == "" {
		return "", nil
	}
	return t.Frame, CanonSoFar(turns, idx)
}
