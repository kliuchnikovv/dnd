package rubric

// TurnRecord — снимок одного хода, который подаётся на вход рубрике.
//
// Структура повторяет то, что пишет vignette.Recorder (input, ruling, roll,
// revealed, state_note, beat, ended, end_text, master_output), плюс ключ-ответ
// сцены (SceneTruth) для анти-утечки. Один и тот же record едят и auto, и
// LLM-судьи.
//
// Передаётся по значению: Verdict — чистая функция записи. Это даёт детер-
// минизм, простую сериализацию (для репортов/корпуса) и независимость от
// того, кто и где живёт — сервер, CLI, тест.
type TurnRecord struct {
	// Ввод игрока — что сказано/сделано. Свободный текст или команда.
	Input string

	// Вердикт холодного судьи (judge.Rule). nil-значения у auto-пунктов,
	// которые судье не нужны; для C10 (мир тоже играет) — поле обязательно.
	RulingKind string
	RollDC     int // DC текущего хода (0 если без броска)
	RollMargin int // маржа хода (0 без броска)

	// Бросок в явном виде (nil если не было). Числа — для структурной
	// проверки A2.a (показан ли бросок) и A2.b (честность исхода).
	Roll struct {
		D20, Mod, DC, Total, Margin int
		Natural                     int // 0 если не натуральный (1 или 20); иначе 1 или 20
		Line                        string
	}

	// Что ядро отдало как открытое знание. Здесь НЕТ Scene.Truth и закрытых
	// тиров — это и есть канал «правды нет у Мастера». D13 сверяется здесь.
	Revealed []string

	// Нейтральное физическое положение/инвентарь/беат. Помогает A4.a: даже
	// на провале что-то должно произойти (смена position/beat/стоимости).
	StateNote string

	// Событие эскалации (hold: голос просит / льстит / грозит). Может
	// стригерить сюжетный бит, который должен быть виден игроку (C11/C12).
	Beat string

	// Развязка.
	Ended   bool
	EndText string

	// Готовая проза Мастера ПОСЛЕ стража. Это и есть объект оценки A1/A2/A3/
	// A4/B5-B7/C8-C12/D13. Если пусто — был выключен Мастер (CLI без ключа):
	// auto-пункты по структуре можно посчитать, LLM-пункты — нельзя.
	MasterOutput string

	// Ключ-ответ сцены: правда (Scene.Truth) для D13. Не уходит Мастеру и
	// живёт ТОЛЬКО в eval'е и в страже (ADR-0008).
	SceneTruth string

	// Дополнительный ключ-ответ: «закрытые тиры» виньетки и т. п. Исполь-
	// зуется D13 как «не выдавать того, что игрок не заслужил открыть».
	ClosedTiers []string

	// Враг/NPC бросил в этом ходу — для C10. Если false, C10 N/A в этом ходу.
	NpcRolled bool
	NpcRoll   struct {
		D20, Margin int
	}

	// ExpectsDie — на этом ходу Мастер говорит о кости (например, на старте:
	// «бросаю в терминале»). Тогда A2 применим, хотя броска ещё не было:
	// проверяется, что кость показана игроку как честная. В Эталоне на старте
	// тег A2 как раз за это.
	ExpectsDie bool

	// EtalonTags — пункты Эталона, которые сработали у Мастера-человека на
	// этом ходу (скобки в документе). Верхняя планка для сравнения: ИИ-Мастер
	// должен вытянуть не меньше.
	EtalonTags []Item
}

// HasRoll — была ли в этом ходу проверка с броском. На таких ходах применимы
// A2.a (показан ли бросок), A2.b (честность исхода), A4 (fail-forward).
func (r TurnRecord) HasRoll() bool { return r.Roll.Line != "" }

// IsTotalFailure — провал с большим отрицательным запасом. Маржа считается по
// виньетке-dnd5e: < -4 это «мимо/ценой крови», -1..-4 это «вышло, но с ценой».
// Эти границы совпадают с описанием A4.a и A4.b в Эталоне.
func (r TurnRecord) IsTotalFailure() bool { return r.HasRoll() && r.Roll.Margin < -4 }

// IsPartialSuccess — вышло, но с ценой (маржа -1..-4). A4.b требует, чтобы
// цена была показана.
func (r TurnRecord) IsPartialSuccess() bool {
	return r.HasRoll() && r.Roll.Margin >= -4 && r.Roll.Margin < 0
}

// IsSuccess — зачётный бросок (маржа >= 0). На успехе A4.a не обязывает
// ничего рождать, но B5/B7 ждут, что успех = откровение, а не «ок».
func (r TurnRecord) IsSuccess() bool { return r.HasRoll() && r.Roll.Margin >= 0 }
