// prompts.go — шаблоны системных промптов для LLM-судьи по каждому мягкому
// пункту Эталона. Все промпты — на русском, потому что Эталон и всё
// проектирование ведутся на нём; смена языка промпта — отдельная задача.
//
// Контракт:
//
//   - один item = один системный промпт (item-specific) + один и тот же формат
//     пользовательского ввода (TurnRecord);
//   - ответ модели = строгий JSON: {"outcome": "pass"|"fail"|"na",
//     "reason": "..."}, ничего больше.
//   - температура 0 (детерминизм внутри сессии) — ставит вызывающий.
//
// Почему НЕ один общий промпт: рубрика намеренно многопунктовая, и каждый
// пункт имеет СВОЙ якорь и СВОЙ сигнал провала. Смешивать в одной формулировке
// — значит получить «общий pass», который не отличить от «оценки по
// совокупности». Эталон прямо просит per-item pass/fail/na (§«Эвал ИИ-мастера»
// в Эталоне).

// ─── Имена констант, чтобы не дублировать в YAML/JSON-сводках ────────

