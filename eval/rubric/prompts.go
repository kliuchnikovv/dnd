// itemSpec — пара (title, body) для каждого мягкого пункта. Hard items
// (A2/A3/A4/D13) тут не представлены — они auto, и LLM по ним не вызывается.
type itemSpec struct {
	title string
	body  string
}

func specFor(item Item) (itemSpec, bool) {
	switch item {
	case A1:
		return itemSpec{"A1", itemA1}, true
	case B5:
		return itemSpec{"B5", itemB5}, true
	case B6:
		return itemSpec{"B6", itemB6}, true
	case B7:
		return itemSpec{"B7", itemB7}, true
	case C8:
		return itemSpec{"C8", itemC8}, true
	case C9:
		return itemSpec{"C9", itemC9}, true
	case C10:
		return itemSpec{"C10", itemC10}, true
	case C11:
		return itemSpec{"C11", itemC11}, true
	case C12:
		return itemSpec{"C12", itemC12}, true
	}
	return itemSpec{}, false
}

// buildSystemForItem — собирает system-prompt под конкретный пункт. К общему
// формату ответа добавляется тело пункта (якорь Эталона) и явные сигналы
// pass/fail для этой конкретной оценки.
//
// Возврат пустой строки + ok=false означает «этот пункт — структурный
// (A2/A3/A4/D13), LLM звать не надо».
func buildSystemForItem(item Item) (string, bool) {
	s, ok := specFor(item)
	if !ok {
		return "", false
	}
	return roleSystem + "\n\nЯкорь:\n" + s.title + ". " + s.body, true
}

// buildUserForItem — формат пользовательского сообщения. Тот же для всех
// пунктов: текстовое представление TurnRecord. Модель не получает JSON-схему
// сцены или скрытых полей; у неё есть только то, что положено по capability
// роли (ReadCandidateLine / ReadPlayerInput / ReadScenePublic /
// ReadMechanicalOutcome), плюс технические поля roll/Margin для оценки.
//
// Не выводим SceneTruth/ClosedTiers — D13 проверяется структурно в AutoJudge
// и не через эту LLM (принцип: судья не видит того, что оценивает на
// честность).
func buildUserForItem(item Item, rec TurnRecord) string {
	var b strings.Builder
	fmt := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	fmt(userHeader, item)
	if rec.HasRoll() {
		fmt("Бросок: %s. Маржа: %+d.\n", rec.Roll.Line, rec.Roll.Margin)
	}
	if rec.MasterOutput != "" {
		fmt("Прозы Мастера:\n—\n%s\n—\n", rec.MasterOutput)
	} else {
		fmt("Прозы Мастера нет (Мастер выключен или ещё не дошёл).\n")
	}
	fmt("Ввод игрока:\n—\n%s\n—\n", rec.Input)
	if len(rec.Revealed) > 0 {
		fmt("Открытое знание (revealed ядром):\n%s\n", strings.Join(rec.Revealed, " · "))
	}
	if rec.StateNote != "" {
		fmt("Нейтральное положение: %s\n", rec.StateNote)
	}
	if rec.Beat != "" {
		fmt("Беат сцены: %s\n", rec.Beat)
	}
	if rec.NpcRolled {
		fmt("Противник бросил: d20=%d, маржа=%+d.\n", rec.NpcRoll.D20, rec.NpcRoll.Margin)
	}
	return b.String()
}
