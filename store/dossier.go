package store

// Dossier — дневник сущности: то, чем она располагает в разговоре, и как
// относится к парти.
//
// Два слоя, и разделение обязательно (§6.5). Мировой слой (PartyID пуст)
// держит объективное: голос, роль. Отношенческий слой (PartyID задан) держит
// то, что у этой сущности сложилось с ЭТОЙ парти: расположение, впечатления,
// незакрытые дела. Кузнец может любить одну парти и ненавидеть другую, и это
// две разные строки, а не одно поле.
//
// Дневник НИКОГДА не является источником истины для фактов. Долги, ранения,
// инвентарь, флаги живут в каноне; дневник держит впечатления, тон и то, о чём
// человек готов говорить. Тогда дрейф пересказа безвреден: если дневник забыл
// сумму долга, канон её помнит.
type Dossier struct {
	EntityID EntityID `json:"entity_id"`
	// PartyID пуст для мирового слоя.
	PartyID string `json:"party_id"`
	Kind    string `json:"kind"` // npc | location | character | faction

	// Voice переопределяет голос сущности, если задан.
	Voice string `json:"voice"`
	// Disposition — расположение к парти. Отношенческий слой.
	Disposition int `json:"disposition"`
	// KnowsAbout — КЛЮЧИ фактов, которые эта сущность знает. Ключи, а не
	// проза: «знает ли кузнец, что мы убили шерифа» — вопрос механический,
	// он гейтит диалог, и проверять его должен движок, а не модель.
	//
	// Знать не значит рассказать: условия выдачи задаёт fact_holders.gate.
	KnowsAbout []FactID `json:"knows_about"`
	// OpenThreads — незакрытое с этой парти: обещания, долги, угрозы. То, из
	// чего у разговора появляется продолжение.
	OpenThreads []string `json:"open_threads"`
	// TalksAbout — безобидные темы, которые сущность поднимает сама. Это и
	// есть топливо светского разговора: без него персонажу нечего сказать, и
	// он либо молчит, либо начинает выдумывать.
	TalksAbout []string `json:"talks_about"`
	// Summary — впечатления от прошлых встреч. Проза, и потому не истина.
	Summary string `json:"summary"`

	Version int `json:"version"`
}

// DossierKey — составной ключ таблицы. Пустая парти означает мировой слой.
type DossierKey struct {
	EntityID EntityID
	PartyID  string
}

func (d Dossier) Key() DossierKey {
	return DossierKey{EntityID: d.EntityID, PartyID: d.PartyID}
}
