package cli

// Свободная проба: ввод, которого словарь не выражает.
//
// Раньше здесь стоял отказ — «так не получится: словарь такого не покрывает».
// Он защищал состояние, но платил за это тем, что рубил исследование: игрок
// пробовал, а мир отвечал служебным языком, что так нельзя (ADR-0003, T1).
//
// Проба приземляется всегда. Худший её исход — «пробуешь, ничего не выходит»
// голосом мира, и это исход в фикшене, а не сообщение об устройстве игры.

// probeFallback — отклик на пробу, когда авторского текста нет и Мастера нет.
// Игра без моделей обязана работать как работала, а молчание игрок читает как
// поломку.
const probeFallback = "Вы пробуете — и ничего из этого не выходит."

// resolveProbe разрешает свободную пробу.
//
// Хода проба не тратит: наблюдение бесплатно, как look. Тика часов, счётчика
// холостых ходов и записи в журнал команд здесь нет — команды не было.
func (s *Session) resolveProbe(probe string) {
	// probe ещё не читается: маршрут пробы к авторскому содержимому и проза
	// Мастера приходят следующей фазой. Пока приземление детерминированное —
	// и это же поведение остаётся правдой для игры без моделей.
	_ = probe
	s.emitText(EventProse, probeFallback+"\n")
	// Ход не состоялся, но модель по недоверенному вводу уже высказалась —
	// и инъекция живёт ровно здесь. Строка аудита пишется без команды и без
	// вердикта: ядру этот ввод не дошёл.
	s.journalAudit("")
}
