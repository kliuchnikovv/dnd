package cli

import (
	"fmt"
	"io"
)

// EventKind — что это за строка вывода. Без вида и автора метку говорящего
// пришлось бы восстанавливать разбором напечатанного текста, то есть парсить
// собственный вывод.
type EventKind string

const (
	EventScene   EventKind = "scene"   // описание места
	EventProse   EventKind = "prose"   // проза Мастера об исходе хода
	EventSpeech  EventKind = "speech"  // прямая речь: NPC или игрок
	EventSystem  EventKind = "system"  // справка, факты, часы, состояние
	EventRefusal EventKind = "refusal" // «нельзя: …»
	EventPrompt  EventKind = "prompt"  // игра спросила: слот обвинения, уточнение
	// EventOptions — набор вариантов хода. Отдельный вид по той же причине,
	// что EventPrompt: это не строка транскрипта, а панель, которая себя
	// заменяет каждый ход. В потоке она копилась бы дюжинами устаревших копий.
	EventOptions EventKind = "options"
	EventNote    EventKind = "note" // поломка надстройки: «Мастер промолчал»
	// EventHunch — подсказка чутья: мысль самого игрока, а не чья-то речь.
	// Отдельный вид, потому что автора у неё нет ни одного из существующих:
	// это не мир (Мастер), не персонаж и не служебный вывод.
	EventHunch EventKind = "hunch"
)

// Event — единица вывода. Text уже отрендерен: приёмник его не собирает и не
// разбирает, а показывает. Так построчный режим остаётся побайтово прежним.
type Event struct {
	Kind    EventKind
	Speaker string // «Берн, стражник» либо «Вы»; только у EventSpeech
	Text    string
}

// Sink — куда уходит вывод сессии. Интерфейс нужен, чтобы полноэкранный режим
// был вторым приёмником, а не вторым форматом вывода.
type Sink interface{ Emit(Event) }

// TextSink печатает событие как есть. Это сегодняшнее поведение игры целиком:
// вид и автор ему не нужны, потому что текст уже собран.
type TextSink struct{ W io.Writer }

func (t TextSink) Emit(e Event) { fmt.Fprint(t.W, e.Text) }

// SpeakerOf — кто автор события. Пусто у служебного вывода: подписывать
// список команд чьим-то именем значит врать об авторстве.
//
// Живёт в cli, а не у приёмника, потому что авторство — свойство события.
// Пока функция принадлежала полноэкранному режиму, построчная запись обязана
// была её продублировать, а два ответа на один вопрос разъезжаются молча.
func SpeakerOf(e Event) string {
	switch e.Kind {
	case EventSpeech:
		return e.Speaker
	case EventProse, EventScene:
		return MasterName
	case EventHunch:
		// Автор у чутья есть (в Speaker), но метка блока не ставится: пометка
		// уже стоит в самой строке, потому что построчный режим меток автора
		// не печатает и там мысль иначе слилась бы с прозой. Вторая метка
		// сверху была бы тем же удвоением имени, каким страдала подсказка
		// напарника.
		return ""
	case EventRefusal:
		// Отказ мира произносит Мастер и подписан им в данных. Служебный
		// отказ — «не понял», «переводчик недоступен» — автора не несёт: это
		// про инструмент, а не про мир, и подписывать его Мастером значит
		// врать игроку о причине.
		return e.Speaker
	default:
		return ""
	}
}
