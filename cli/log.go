package cli

import (
	"fmt"
	"io"
	"strings"
)

// Запись игры — читаемый транскрипт прогона: что игрок писал и что ему
// отвечали.
//
// Отдельно от журнала (ADR-0002) намеренно. Журнал машинный: он хранит правду
// реплея — интенты — и аудит недоверенного ввода. Вывода, который игрок ВИДЕЛ,
// там нет вовсе: сцену, прозу, бросок, находки и отказы печатает код. Запись
// отвечает на другой вопрос и потому живёт отдельно, а не расширяет журнал
// шестым видом строки.

// GameLog — запись одного прогона.
//
// Пишет всё, что игрок видел, включая механику: броски, находки, цену. Запись
// без них не отвечает на вопрос «почему он тогда так поступил», а ради этого
// вопроса она и нужна.
type GameLog struct {
	w io.Writer
	// prev — автор последней записанной строки. Подпись ставится при смене
	// говорящего: подпись над каждой строкой одного и того же — шум.
	prev string
	// unsigned — последний написанный блок был служебным (без подписи). Нужен,
	// чтобы решить, ставить ли пустую строку-разделитель перед следующим
	// блоком: между двумя служебными блоками подряд (например «Что известно» и
	// «При себе») разделитель не нужен, а на стыке с репликой Мастера — нужен,
	// иначе служебный текст слипнется с прозой и прочитается её продолжением.
	unsigned bool
	// broken — о поломке уже сказано. Жаловаться каждой строкой значит топить
	// в шуме сам вывод игры.
	broken bool
	// note — куда сказать о поломке. Пустой означает молчание, и это законно
	// только в тестах самой записи.
	note func(string)
}

// NewGameLog открывает запись. Заголовок пишется сразу: пустой прогон должен
// оставлять файл, по которому видно, что прогон был.
func NewGameLog(w io.Writer, header string) *GameLog {
	l := &GameLog{w: w}
	if strings.TrimSpace(header) != "" {
		l.write(header + "\n")
	}
	return l
}

// turn отмечает начало хода. Номер тот же, что у журнала команд: по нему
// читаемая строка сходится с машинной, и разбор идёт от одной к другой.
func (l *GameLog) turn(n int) {
	if l == nil {
		return
	}
	l.prev = ""
	l.unsigned = false
	l.write(fmt.Sprintf("\n[ход %d]\n", n))
}

// input записывает то, что ввёл игрок.
//
// Пишется ЗДЕСЬ, а не событием, и это несущее: событие напечаталось бы на
// экране вторым эхом — игрок и так видит то, что набрал, — и вывод игры
// перестал бы быть побайтово прежним.
func (l *GameLog) input(line string) {
	if l == nil || strings.TrimSpace(line) == "" {
		return
	}
	l.prev = PlayerName
	l.write(PlayerName + ": " + strings.TrimSpace(line) + "\n")
}

// event записывает то, что игра ответила.
func (l *GameLog) event(e Event) {
	if l == nil {
		return
	}
	// Панель вариантов не строка транскрипта, а панель: она себя заменяет
	// каждый ход, и в потоке копилась бы дюжинами устаревших копий. Та же
	// причина, по которой её отдельно выделили видом события.
	if e.Kind == EventOptions {
		return
	}
	text := strings.TrimRight(e.Text, "\n")
	if strings.TrimSpace(text) == "" {
		return
	}
	who := SpeakerOf(e)
	lines := strings.Split(text, "\n")
	if who == "" {
		// Служебный вывод (EventSystem и подобные) печатается БЕЗ отступа —
		// вровень с левым краем, а не под чужой подписью. Отступ в этой записи
		// не украшение, а означает принадлежность: подписанный текст стоит
		// с отступом под своей подписью, и печатать служебный список тем же
		// отступом значит визуально приписать его тому, чья подпись выше, даже
		// если l.prev после этого блока сбрасывается. Раз подписать список
		// НЕЧЬИМ именем нельзя (SpeakerOf для него пуст), формат обязан сказать
		// «это не чья-то реплика» самим видом строки — без отступа.
		if !l.unsigned && l.prev != "" {
			l.write("\n")
		}
		for _, line := range lines {
			l.write(line + "\n")
		}
		l.unsigned = true
		l.prev = ""
		return
	}
	// Пустой автор — это служебный вывод, и он значит СБРОС атрибуции, а не
	// «тот же говорящий, что и раньше»: возврат выше уже это отработал. Здесь
	// же — обычная подписанная реплика: если перед ней стоял служебный блок,
	// отделяем её пустой строкой по той же причине (отступ без разделителя
	// не спасает от слипания текста на глаз).
	if l.unsigned {
		l.write("\n")
	}
	if who != l.prev {
		l.write(who + ":\n")
	}
	l.prev = who
	l.unsigned = false
	for _, line := range lines {
		l.write("  " + line + "\n")
	}
}

// write — единственное место, где запись трогает диск. Поломка ход не рушит:
// игра, падающая из-за надстройки, хуже игры без надстройки. Но и не молчит:
// молча откатываясь, запись выглядит рабочей при пустом файле.
func (l *GameLog) write(s string) {
	if l.broken {
		return
	}
	if _, err := io.WriteString(l.w, s); err != nil {
		l.broken = true
		if l.note != nil {
			l.note("запись игры: " + err.Error())
		}
	}
}
